"""The clips, pose to pose. Frames at 30 fps; Rive units (screen px / 0.7)."""
from author import (BODY, CHAR, EL, ER, HL, HR, LBM, LOOK, LTL, LTR, RBM, RTL, RTR, TUCK_L, TUCK_R, Clip,
                    lid)


def near(c, *keys):
    c.k(CHAR, "sx", *keys)
    c.k(CHAR, "sy", *keys)


def happy(c, on, full, off, done):
    """^ ^ from `on` (full by `full`), back to pills from `off` (by `done`)."""
    for bm in (LBM, RBM):
        c.k(bm, "vy", (on, 30, "o"), (full, -12, "h"), (off, -12), (done, 30, "h"))
        c.k(bm, "rad", (on, 0, "o"), (full, 8, "h"), (off, 8), (done, 0, "h"))
    return [(on, 100, "o"), (full, 115, "h"), (off, 115), (done, 100, "h")], \
        [(on, 100, "o"), (full, 60, "h"), (off, 60), (done, 100, "h")]


